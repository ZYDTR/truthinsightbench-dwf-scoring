# ---------------------------------------------------------------- my LS
def my_ls(t_sec, Y, f_hz):
    """Normalized LS power, (S,F). Y: (N,) or (N,S). Independent implementation."""
    t_sec = np.asarray(t_sec, float)
    Y = np.asarray(Y, float)
    if Y.ndim == 1:
        Y = Y[:, None]
    n = Y.shape[0]
    Yc = Y - Y.mean(axis=0, keepdims=True)
    var = np.mean(Yc * Yc, axis=0)                     # per-series variance
    F = np.asarray(f_hz, float).size
    out = np.empty((Y.shape[1], F))
    for lo in range(0, F, 512):
        hi = min(lo + 512, F)
        w = 2.0 * np.pi * f_hz[lo:hi]
        wt = np.outer(w, t_sec)                        # (F,N)
        c, s = np.cos(wt), np.sin(wt)
        CC = (c * c).mean(axis=1)
        SS = (s * s).mean(axis=1)
        CS = (c * s).mean(axis=1)
        tau = 0.5 * np.arctan2(2.0 * CS, CC - SS)
        c2 = np.cos(wt - tau[:, None])
        s2 = np.sin(wt - tau[:, None])
        cc = (c2 * c2).mean(axis=1)
        ss = (s2 * s2).mean(axis=1)
        YC = (Yc.T @ c2.T) / n                         # (S,F)
        YS = (Yc.T @ s2.T) / n
        p = YC * YC / cc[None, :] + YS * YS / ss[None, :]
        out[:, lo:hi] = p / var[:, None]
    return out


def ar1_lfilter(n, a, s, rng):
    """AR(1) with per-step innovation std s*sqrt(1-a^2), generated by lfilter."""
    e = rng.normal(0.0, s * np.sqrt(max(1.0 - a * a, 1e-12)), n)
    x = lfilter([1.0], [1.0, -a], e)
    return x


def ar1_ref(n, a, s, rng):
    """Explicit recursion reference (small n only)."""
    e = rng.normal(0.0, s * np.sqrt(max(1.0 - a * a, 1e-12)), n)
    x = np.zeros(n)
    for i in range(1, n):
        x[i] = a * x[i - 1] + e[i]
    return x


def ar1_fit(y):
    y = np.asarray(y, float)
    y = y - y.mean()
    den = float(np.dot(y[:-1], y[:-1]))
    a = float(np.clip(np.dot(y[:-1], y[1:]) / den, -0.99, 0.99))
    return a, float(np.std(y))


def sinusoid_amp_phase(t_min, y, f_uhz):
    """LS sinusoid amplitude/phase after linear detrend. y = A cos(wt - phi)."""
    t_sec = np.asarray(t_min, float) * 60.0
    y = np.asarray(y, float)
    tc = t_sec - t_sec.mean()
    p = np.polyfit(tc, y, 1)
    yd = y - np.polyval(p, tc)
    w = 2.0 * np.pi * f_uhz * 1e-6
    X = np.column_stack([np.cos(w * t_sec), np.sin(w * t_sec)])
    beta, *_ = np.linalg.lstsq(X, yd, rcond=None)
    return float(np.hypot(beta[0], beta[1])), float(np.arctan2(beta[1], beta[0])), yd


def rayleigh_R(phases):
    z = np.exp(1j * np.asarray(phases, float))
    return float(np.abs(z.sum()) / len(z))


def main():
    t0 = time.time()
    out = {}
    tr = pd.read_csv(DATA / "pass_residual_traces.tsv", sep="\t")
    passes = sorted(tr.pass_id.unique())
    TS = {p: tr.loc[tr.pass_id == p, "relative_time_min"].to_numpy() for p in passes}
    YS = {p: {k: tr.loc[tr.pass_id == p, c].to_numpy() for k, c in MODELS.items()} for p in passes}

    # ---- validate my LS against scipy on real data (3 pass/model combos)
    f_band = np.arange(BAND[0], BAND[1] + 1e-9, 1.0)
    val = []
    for p, k in [("pass_01", "A"), ("pass_07", "C"), ("pass_22", "B")]:
        ref = lombscargle(TS[p] * 60.0, YS[p][k] - YS[p][k].mean(),
                          2 * np.pi * f_band * 1e-6, normalize=True)
        mine = my_ls(TS[p] * 60.0, YS[p][k], f_band * 1e-6)[0]
        val.append(float(np.max(np.abs(ref - mine))))
    # validate surrogate generator
    rngv = np.random.default_rng(1)
    a0, s0 = 0.5, 0.02
    x1 = ar1_lfilter(60, a0, s0, np.random.default_rng(2))
    x2 = ar1_ref(60, a0, s0, np.random.default_rng(2))
    ar1_check = float(np.max(np.abs(x1 - x2)))
    out["self_validation"] = {
        "max_abs_diff_my_ls_vs_scipy": max(val),
        "max_abs_diff_lfilter_vs_recursion_ar1": ar1_check,
    }
    print("validation:", out["self_validation"], flush=True)

    # =====================================================================
    # Q1: band-mean power per pass and median per-pass percentile vs AR(1)
    #     (860-1310 uHz, 451 bins)
    # =====================================================================
    N_S = 1000
    rng = np.random.default_rng(SEED)
    band_obs, band_pct = {}, {}
    for k in MODELS:
        band_obs[k], band_pct[k] = {}, {}
        for p in passes:
            y = YS[p][k]
            obs = float(my_ls(TS[p] * 60.0, y, f_band * 1e-6)[0].mean())
            a, s = ar1_fit(y)
            S = np.column_stack([ar1_lfilter(len(y), a, s, rng) for _ in range(N_S)])
            nb = my_ls(TS[p] * 60.0, S, f_band * 1e-6).mean(axis=1)
            band_obs[k][p] = obs
            band_pct[k][p] = float((nb < obs).mean())
    out["Q1_band_percentile"] = {}
    for k in MODELS:
        pct = np.array([band_pct[k][p] for p in passes])
        out["Q1_band_percentile"][k] = {
            "median_percentile": float(np.median(pct)),
            "n_gt_0.95": int((pct > 0.95).sum()),
            "n_gt_0.99": int((pct > 0.99).sum()),
            "sign_test_p_vs_0.5": float(stats.binomtest(int((pct > 0.5).sum()), 22, 0.5).pvalue),
            "k_above_0.5": int((pct > 0.5).sum()),
            "mediation_of_band_mean_power": float(np.median([band_obs[k][p] for p in passes])),
        }
    print("Q1 done", flush=True)

    # =====================================================================
    # Q2: stacked spectrum global peak (mean of per-pass normalized spectra)
    # =====================================================================
    f_full = np.arange(200.0, 3000.0, 1.0)
    spectra = {k: {p: my_ls(TS[p] * 60.0, YS[p][k], f_full * 1e-6)[0] for p in passes}
               for k in MODELS}
    out["Q2_stacked_peak"] = {}
    for k in MODELS:
        St = np.mean([spectra[k][p] for p in passes], axis=0)
        i = int(np.argmax(St))
        med_res = 210.9704641350211
        near = 0
        passpeaks = []
        for p in passes:
            ip = int(np.argmax(spectra[k][p]))
            passpeaks.append(float(f_full[ip]))
            near += int(abs(f_full[ip] - f_full[i]) <= med_res)
        n_uniform_peaks = 2800.0 - 2.0 * med_res
        out["Q2_stacked_peak"][k] = {
            "stacked_peak_uhz": float(f_full[i]),
            "stacked_peak_power": float(St[i]),
            "n_passes_peaking_within_1_res_elem": int(near),
            "pass_peak_freq_median_uhz": float(np.median(passpeaks)),
            "pass_peak_freq_q25_q75": [float(np.percentile(passpeaks, 25)),
                                       float(np.percentile(passpeaks, 75))],
            "naive_uniform_expected_count": 22 * min(1.0, 2 * med_res / 2800.0),
            "binomial_p_near_peak_vs_uniform_chance": float(
                stats.binomtest(int(near), 22, min(1.0, 2 * med_res / 2800.0)).pvalue),
        }
    print("Q2 done", flush=True)

    # =====================================================================
    # Q3: Rayleigh phase coherence at 1010 / 1210 uHz
    # =====================================================================
    out["Q3_rayleigh"] = {}
    rngu = np.random.default_rng(7)
    n_mc = 20000
    for f0 in (1010.0, 1210.0):
        out["Q3_rayleigh"][str(f0)] = {}
        for k in MODELS:
            ph = np.array([sinusoid_amp_phase(TS[p], YS[p][k], f0)[1] for p in passes])
            R = rayleigh_R(ph)
            z = np.abs(np.exp(1j * rngu.uniform(0, 2 * np.pi, size=(n_mc, 22))).sum(axis=1)) / 22
            out["Q3_rayleigh"][str(f0)][k] = {
                "R": R,
                "p_monte_carlo_uniform": float((z >= R).mean()),
                "circular_Kuiper_note": "reported p uses the uniform-phase null, matching the claim",
            }
    print("Q3 done", flush=True)

    # =====================================================================
    # Q4: comb test - per-pass percentile within own band at the 4 core freqs
    # =====================================================================
    core = [1010.0, 1060.0, 1110.0, 1210.0]
    out["Q4_comb"] = {}
    for k in MODELS:
        idx = [int(np.argmin(np.abs(f_band - f))) for f in core]
        per_pass = []
        for p in passes:
            Pb = spectra[k][p][(f_full >= 860) & (f_full <= 1310)]  # from full grid
            per_pass.append([float((Pb < Pb[j]).mean()) for j in idx])
        x = np.array([np.mean(v) for v in per_pass])
        out["Q4_comb"][k] = {
            "median_pass_mean_pct_in_band": float(np.median(x)),
            "k_above_0.5": int((x > 0.5).sum()),
            "sign_test_p": float(stats.binomtest(int((x > 0.5).sum()), 22, 0.5).pvalue),
        }
    print("Q4 done", flush=True)

    # =====================================================================
    # Q5: coincidence check - the "stacked peak at 489 uHz is the harmonic of
    #     the 1010 uHz fit" story.  Amplitude ratios A_1010/A_505 per pass,
    #     plus an independent AR(1) null for the ratio.
    # =====================================================================
    out["Q5_1010_vs_505"] = {}
    for k in MODELS:
        amps_505, amps_1010 = [], []
        for p in passes:
            amps_505.append(sinusoid_amp_phase(TS[p], YS[p][k], 505.0)[0])
            amps_1010.append(sinusoid_amp_phase(TS[p], YS[p][k], 1010.0)[0])
        amps_505 = np.array(amps_505)
        amps_1010 = np.array(amps_1010)
        ratios = amps_1010 / np.where(amps_505 > 0, amps_505, np.nan)
        # AR(1) null for the median ratio
        rngn = np.random.default_rng(11)
        nullmed = []
        for _ in range(200):
            r = []
            for p in passes:
                y = YS[p][k]
                a, s = ar1_fit(y)
                yy = ar1_lfilter(len(y), a, s, rngn)
                a5 = sinusoid_amp_phase(TS[p], yy, 505.0)[0]
                a10 = sinusoid_amp_phase(TS[p], yy, 1010.0)[0]
                r.append(a10 / a5 if a5 > 0 else np.nan)
            nullmed.append(np.nanmedian(r))
        nullmed = np.array(nullmed)
        med = float(np.nanmedian(ratios))
        out["Q5_1010_vs_505"][k] = {
            "median_ratio_A1010_over_A505": med,
            "n_passes_ratio_gt_1": int(np.nansum(ratios > 1)),
            "ar1_null_median_ratio_q2.5_q50_q97.5": [float(np.percentile(nullmed, q)) for q in (2.5, 50, 97.5)],
            "p_median_ratio_vs_ar1": float((nullmed >= med).mean()),
            "n_surrogate_median_draws": len(nullmed),
        }
    print("Q5 done", flush=True)

    # =====================================================================
    # Q6: spectral slope per pass (sanity on sec6 claim)
    # =====================================================================
    out["Q6_slopes"] = {}
    lf = np.log10(f_full)
    for k in MODELS:
        sl = []
        for p in passes:
            P = spectra[k][p]
            s, _ = np.polyfit(lf, np.log10(np.maximum(P, 1e-300)), 1)
            sl.append(float(s))
        out["Q6_slopes"][k] = {"median": float(np.median(sl)),
                               "q25": float(np.percentile(sl, 25)),
                               "q75": float(np.percentile(sl, 75))}

    out["runtime_sec"] = round(time.time() - t0, 1)
    (RES / "_verify_spectral_recompute.json").write_text(json.dumps(out, indent=2) + "\n")
    print(json.dumps(out, indent=1))
    print("runtime", out["runtime_sec"])


if __name__ == "__main__":
    main()